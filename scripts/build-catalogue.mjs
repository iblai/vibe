#!/usr/bin/env node
// Generate docs/catalogue.md — every skill, by folder, with its kind and
// description — from the SKILL.md frontmatter. Run after adding or moving a
// skill; check-skill-tables.mjs verifies the result matches skills/.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ROOT, CATEGORIES, listSkills } from "./lib/skills.mjs";

const TITLES = {
  start: ["Start", "Get an app running: the first conversation, credentials, sign-in, the starter, the REST bridge, keeping skills current."],
  agents: ["Agents", "Chat with agents, browse and create them, and configure every setting tab — with a screen (`iblai-vibe-*`) or headless (`iblai-api-*`)."],
  users: ["Users", "Profiles, custom per-user data, memories, roles and admins, invitations, notifications, onboarding."],
  organizations: ["Organizations", "Org settings and custom metadata, branding, integrations and tokens, CRM."],
  billing: ["Billing", "How you are charged, spend caps, and the three ways to charge your users."],
  analytics: ["Analytics", "Usage, users, topics, transcripts, costs, audit, reports — org-wide or per agent."],
  content: ["Content", "Courses, catalog, credentials, admissions — and other LMSs."],
  ship: ["Ship", "Test, deploy, native builds, app stores, icons, polish, self-hosting."],
  security: ["Security", "Authorized-use security work, unrelated to the platform."],
};
const KIND = { ui: "🖥️ ui", api: "🔌 api", guide: "📖 guide", ops: "🛠️ ops", security: "🛡️ security" };

const skills = listSkills();
const fm = (file) => {
  const src = readFileSync(file, "utf8");
  const m = /^---\n([\s\S]*?)\n---\n/.exec(src)?.[1] ?? "";
  const description = /^description:\s*(.*)$/m.exec(m)?.[1]?.replace(/^"|"$/g, "") ?? "";
  const kind = /^\s+kind:\s*([a-z]+)/m.exec(m)?.[1] ?? "";
  return { description, kind };
};
const short = (d) => {
  const s = d.split(/\. |—| – /)[0].replace(/\s+/g, " ").trim();
  return (s.length > 140 ? s.slice(0, 137) + "…" : s).replace(/\|/g, "\\|");
};

let out = `# Skill catalogue

Every skill, by folder — what it does, and whether it has a screen. Generated by
\`node scripts/build-catalogue.mjs\` from each skill's frontmatter; do not edit by
hand. Kinds: 🖥️ **ui** mounts a visual component · 🔌 **api** is headless REST ·
📖 **guide** routes you · 🛠️ **ops** builds and ships · 🛡️ **security**.
See [skill-kinds.md](skill-kinds.md).

| Folder | What it covers | Skills |
|---|---|---|
`;
for (const c of CATEGORIES.order) out += `| [\`${c}/\`](#${c}) | ${TITLES[c][1]} | ${skills.filter((s) => s.category === c).length} |\n`;

for (const c of CATEGORIES.order) {
  const rows = skills.filter((s) => s.category === c);
  out += `\n## ${TITLES[c][0]}\n\n\`skills/${c}/\` — ${TITLES[c][1]}\n\n| Skill | Kind | What it does |\n|---|---|---|\n`;
  for (const s of rows) {
    const { description, kind } = fm(s.file);
    out += `| [\`/${s.name}\`](../skills/${c}/${s.name}/SKILL.md) | ${KIND[kind] ?? kind} | ${short(description)} |\n`;
  }
}
out += `\nTotal: ${skills.length} skills.\n`;
writeFileSync(join(ROOT, "docs", "catalogue.md"), out);
console.log(`docs/catalogue.md: ${skills.length} skills in ${CATEGORIES.order.length} folders`);
